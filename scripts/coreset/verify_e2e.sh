#!/usr/bin/env bash
# End-to-end check that an exported panel works with the UNMODIFIED scoring pipeline,
# and that its weighted estimate lands near the known full-set score.
#
# The statistical claim (does the weighted estimator recover the macro-average?) is
# already established offline by scripts/coreset/validate.py over ~9 held-out families.
# What this script checks is the part offline validation cannot: that the exported
# data/<task>/ directory really drives run_infer_*.sh, that the scorers write per-uid
# files the panel scorer can read, and that the weights are applied to the right items.
#
# To avoid paying for regeneration it reuses each system's EXISTING full-set wavs,
# symlinking just the panel's uids into a panel DECODE_DIR and re-scoring those. The
# generated audio is byte-identical to what a real panel run would produce for those
# items, because it is the same model on the same prompts. The source task is read from
# the panel's own panel.json (both sets share the uttid_N uid scheme, so linking from
# the wrong source would silently score the wrong audio against the panel texts).
#
#   sbatch --job-name=ztts-coreset-e2e --gpus=1 \
#          --cpus-per-task=28 --mem=200G --time=6:00:00 \
#          --chdir="$(pwd)" --output=logs/slurm/ztts-coreset-e2e-%j.out \
#          scripts/coreset/verify_e2e.sh
#
# Override with: E2E_SYSTEMS="zonos2_accurate kokoro", E2E_TASK=clean_mini,
#                E2E_LANGS="en de fr" (default: every language the panel has).
#
# This is a gate: any scoring failure, any system with no scored leaves, fails the job.
set -euo pipefail
[ -f scripts/serve_asr.sh ] || cd "$(dirname "$0")/../.." || exit 1
[ -f scripts/serve_asr.sh ] || { echo "[e2e] ERROR: not at repo root"; exit 1; }

E2E_TASK=${E2E_TASK:-clean_mini}
# One system that was in the selection pool, one from a family held out of it.
E2E_SYSTEMS=${E2E_SYSTEMS:-"zonos2_accurate kokoro"}

if [ -x .venv/bin/python ]; then PY=.venv/bin/python; else PY=python; fi

PANEL_DIR="data/${E2E_TASK}"
[ -f "${PANEL_DIR}/panel.json" ] || { echo "[e2e] ERROR: ${PANEL_DIR}/panel.json not found — export a panel first"; exit 1; }

# The wavs to reuse come from the panel's SOURCE task, recorded in panel.json. A
# user-supplied SRC_TASK may only confirm it, never override it.
panel_src=$("${PY}" -c 'import json,sys; print(json.load(open(sys.argv[1]))["source_task"])' "${PANEL_DIR}/panel.json")
if [ -n "${SRC_TASK:-}" ] && [ "${SRC_TASK}" != "${panel_src}" ]; then
    echo "[e2e] ERROR: SRC_TASK=${SRC_TASK} contradicts ${PANEL_DIR}/panel.json source_task=${panel_src}"
    exit 1
fi
SRC_TASK=${panel_src}

LANGS=${E2E_LANGS:-$(ls -d "${PANEL_DIR}"/*/ 2>/dev/null | xargs -n1 basename | tr '\n' ' ' || true)}
[ -n "${LANGS// /}" ] || { echo "[e2e] ERROR: no languages found under ${PANEL_DIR}"; exit 1; }

job_id="${SLURM_JOB_ID:-$$}"
port_base=$(( 20000 + (job_id % 10000) * 4 ))
export ASR_PORT=$(( port_base + 1 )) WHISPER_PORT=$(( port_base + 2 ))
export ASR_GPU=0 WHISPER_GPU=0 ASR_ROUTING=1
export ASR_GPU_MEM_UTIL=0.35 WHISPER_GPU_MEM_UTIL=0.35
srv="logs/slurm/servers/coreset-e2e-${job_id}"; mkdir -p "${srv}"
export ASR_LOG="${srv}/asr.log" WHISPER_LOG="${srv}/whisper.log"

echo "[e2e] task=${E2E_TASK} src_task=${SRC_TASK} systems='${E2E_SYSTEMS}'"
echo "[e2e] langs: ${LANGS}"

# --- 1. materialize panel DECODE_DIRs from the existing full-set wavs ---------------
for sys in ${E2E_SYSTEMS}; do
    n_link=0; n_miss=0
    for lg in ${LANGS}; do
        src="results/${sys}/${SRC_TASK}/${lg}/wavs"
        [ -d "${src}" ] || continue
        leaf="results/${sys}/${E2E_TASK}/${lg}"
        # Refuse to delete a leaf holding REAL (non-symlink) wavs: results/<sys>/<task>/
        # is exactly where a genuine panel generation run lands, and this verifier must
        # never destroy one. Our own leaves contain only symlinks and score files.
        if [ -d "${leaf}" ] && \
           [ -n "$(find "${leaf}" -name '*.wav' -type f -print -quit 2>/dev/null)" ]; then
            echo "[e2e] ERROR: ${leaf} contains real (non-symlink) wavs — it looks like a"
            echo "[e2e]        genuine panel run. Refusing to delete it; move it aside or"
            echo "[e2e]        use a scratch E2E_TASK."
            exit 1
        fi
        rm -rf "${leaf}"
        dst="${leaf}/wavs"
        mkdir -p "${dst}"
        while read -r uid _rest; do
            if [ -f "${src}/${uid}.wav" ]; then
                ln -sf "$(readlink -f "${src}/${uid}.wav")" "${dst}/${uid}.wav"
                n_link=$((n_link+1))
            else
                n_miss=$((n_miss+1))
            fi
        done < "${PANEL_DIR}/${lg}/text"
    done
    echo "[e2e] ${sys}: linked ${n_link} panel wavs (${n_miss} not generated by this system)"
done

# --- 2. score them with the unmodified pipeline ------------------------------------
. scripts/serve_asr.sh
trap 'stop_asr_server; stop_whisper_server' EXIT INT TERM
start_asr_server || { echo "[e2e] ERROR: ASR server failed"; exit 1; }
maybe_start_whisper || exit 1

for sys in ${E2E_SYSTEMS}; do
    have=""
    for lg in ${LANGS}; do
        if [ -d "results/${sys}/${E2E_TASK}/${lg}/wavs" ] && \
           [ -n "$(ls -A "results/${sys}/${E2E_TASK}/${lg}/wavs" 2>/dev/null || true)" ]; then
            have="${have} ${lg}"
        fi
    done
    [ -n "${have}" ] || { echo "[e2e] ${sys}: nothing to score"; continue; }
    echo "=== [e2e] scoring ${sys} on ${E2E_TASK} ==="
    DECODE_DIR="results/${sys}/${E2E_TASK}" \
        bash run_infer_zonos2_eval.sh --task "${E2E_TASK}" --test_set "${have}"
done
stop_asr_server || true
stop_whisper_server || true
trap - EXIT INT TERM

# --- 3. compare the panel estimate against the known full-set score ----------------
# score_panel.py and compare_e2e.py both exit non-zero when a system produced no scored
# leaves, which fails this job — the gate has teeth on purpose.
for sys in ${E2E_SYSTEMS}; do
    echo
    "${PY}" scripts/coreset/score_panel.py --decode_dir "results/${sys}/${E2E_TASK}" \
            --task "${E2E_TASK}"
done

echo
echo "[e2e] full-set reference numbers for the same systems:"
"${PY}" scripts/coreset/compare_e2e.py --task "${E2E_TASK}" --systems "${E2E_SYSTEMS}"
