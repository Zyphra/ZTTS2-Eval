#!/usr/bin/env bash
# Regenerate the reliability plates + the self-contained HTML gallery.
#
# The tufte_* scripts render edit-distance survival/reliability views from the
# per-leaf `wav_res_ref_text.wer.raw` files (reconstructing exact edit counts with
# run_wer.py's own tokenization). This driver is the deterministic replacement for
# the old hand-run loop: it emits the nine PNGs that build_reliability_gallery.py
# expects into assets/plots/, then assembles assets/reliability_gallery.html.
#
# Inputs are the GT-baseline .wer.raw files (produced by run_gt_zero_shot.sh /
# the scoring pipeline; gitignored but present after scoring). Idempotent.

set -euo pipefail
cd "$(dirname "$0")/.."
REPO_ROOT="$(pwd)"

if [[ -n "${PYTHON:-}" ]]; then
    PY="$PYTHON"
elif [[ -x "$REPO_ROOT/.venv/bin/python" ]]; then
    PY="$REPO_ROOT/.venv/bin/python"
else
    PY="python3"
fi
echo "Using interpreter: $PY"

PLOTS="$REPO_ROOT/assets/plots"
CLEAN_GLOB="results/gt_zero_shot/*/wav_res_ref_text.wer.raw"
VOX_GLOB="results/gt_zero_shot_voxblink/*/wav_res_ref_text.wer.raw"

# Guard: the .raw inputs must exist (they are regenerated by GT scoring).
if ! compgen -G "$CLEAN_GLOB" > /dev/null; then
    echo "ERROR: no $CLEAN_GLOB found. Run scripts/run_gt_zero_shot.sh first to" >&2
    echo "       produce the GT-baseline .wer.raw files the plates read." >&2
    exit 1
fi

# --- Set A: FLEURS-R clean, one series per language ------------------------
echo "[clean] p99 / overlay / smallmultiples / slopegraph (35 langs)"
$PY scripts/tufte_p99.py                     "$CLEAN_GLOB" --label lang -o "$PLOTS/reliability_p99_clean.png"
$PY scripts/tufte_survival_overlay.py        "$CLEAN_GLOB" --label lang -o "$PLOTS/reliability_overlay_clean.png"
$PY scripts/tufte_survival_smallmultiples.py "$CLEAN_GLOB" --label lang -o "$PLOTS/reliability_smallmultiples_clean.png"
$PY scripts/tufte_slopegraph.py              "$CLEAN_GLOB" --label lang --limit 12 -o "$PLOTS/reliability_slopegraph_clean.png"

# --- Set B: VoxBlink2 in-the-wild, one series per language -----------------
if compgen -G "$VOX_GLOB" > /dev/null; then
    echo "[voxblink] p99 / overlay / smallmultiples / slopegraph (21 langs)"
    $PY scripts/tufte_p99.py                     "$VOX_GLOB" --label lang -o "$PLOTS/reliability_p99_voxblink.png"
    $PY scripts/tufte_survival_overlay.py        "$VOX_GLOB" --label lang -o "$PLOTS/reliability_overlay_voxblink.png"
    $PY scripts/tufte_survival_smallmultiples.py "$VOX_GLOB" --label lang -o "$PLOTS/reliability_smallmultiples_voxblink.png"
    $PY scripts/tufte_slopegraph.py              "$VOX_GLOB" --label lang --limit 12 -o "$PLOTS/reliability_slopegraph_voxblink.png"
else
    echo "[voxblink] skipped — no $VOX_GLOB"
fi

# --- Method: same English GT audio, two ASR backends (series = backend) ----
GT_EN="results/gt_zero_shot/en/wav_res_ref_text.wer.raw"
WH_EN="results/whisper_zero_shot/en/wav_res_ref_text.wer.raw"
if [[ -s "$GT_EN" && -s "$WH_EN" ]]; then
    echo "[backend] Qwen3-ASR vs Whisper large-v3 on English GT"
    $PY scripts/tufte_survival_overlay.py "$GT_EN" "$WH_EN" --label set \
        --rename "gt_zero_shot=Qwen3-ASR,whisper_zero_shot=Whisper" \
        --title "Reliability by ASR backend — English GT" \
        -o "$PLOTS/reliability_backend_en.png"
else
    echo "[backend] skipped — need both $GT_EN and $WH_EN"
fi

# --- Assemble the gallery --------------------------------------------------
echo "[gallery] build_reliability_gallery.py"
$PY scripts/build_reliability_gallery.py --plots-dir "$PLOTS" \
    --out "$REPO_ROOT/assets/reliability_gallery.html"
